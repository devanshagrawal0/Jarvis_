import { chromium } from "playwright";
const base = process.argv[2] || "https://nucbox-k8-plus.tail6f924a.ts.net";
const out = process.argv[3] || "D:/jarvis/_newpc/control";
const b = await chromium.launch({ channel: "msedge", headless: true, args: ["--headless=new", "--use-angle=d3d11", "--use-gl=angle", "--enable-gpu", "--ignore-gpu-blocklist"] });
const ctx = await b.newContext({ viewport: { width: 430, height: 932 }, deviceScaleFactor: 3, isMobile: true, hasTouch: true, ignoreHTTPSErrors: true });
const page = await ctx.newPage();
page.on("console", (m) => { if (m.type() === "error") console.log("console.error:", m.text().slice(0, 160)); });
await page.goto(`${base}/app.html`, { waitUntil: "load", timeout: 60000 });
await page.evaluate(() => localStorage.setItem("jarvis.mobile.coach", "off"));
await page.reload({ waitUntil: "load" });
await page.waitForTimeout(2500);
await page.getByRole("button", { name: "Control" }).click();
await page.waitForTimeout(11000);
console.log("build", await page.locator(".app").getAttribute("data-build"));
console.log("hero:", (await page.locator(".pchero-foot").innerText().catch(() => "?")).replace(/\s+/g, " "), "| pins:", (await page.locator(".pins").innerText().catch(() => "?")).replace(/\s+/g, " "), "| sections:", await page.locator(".secbtn").count());
await page.screenshot({ path: `${out}-home.png` });
// open the Apps sheet
await page.locator(".secbtn", { hasText: "Apps" }).click();
await page.waitForTimeout(3500);
console.log("apps sheet tiles:", await page.locator(".apptile").count(), "icons:", await page.locator(".apptile-img").evaluateAll((i) => i.filter((x) => x.complete && x.naturalWidth > 0).length));
await page.screenshot({ path: `${out}-apps.png` });
await b.close();
